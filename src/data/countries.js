// Structural exposure index for the map: oil-weighted blend of oil and LNG exposure.
export function exposureIndex(c) {
  if (!c || c.role === "producer") return null;
  return Math.min(1, 0.7 * c.hzOil + 0.3 * c.hzLng);
}
